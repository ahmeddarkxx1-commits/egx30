export function AssetLogo({ symbol, fallbackIcon, size = 24, containerSize = 38 }) {
  const cleanSymbol = symbol ? symbol.toUpperCase().trim() : '';
  const logoUrl = assetLogoMap[cleanSymbol] || assetLogoMap[cleanSymbol.split('/')[0]];

  return (
    <div 
      style={{ 
        width: `${containerSize}px`, 
        height: `${containerSize}px`, 
        borderRadius: '50%', 
        background: 'rgba(255,255,255,0.06)', 
        display: 'flex', 
        alignItems: 'center', 
        justifyContent: 'center', 
        overflow: 'hidden',
        flexShrink: 0
      }}
    >
      {logoUrl ? (
        <img 
          src={logoUrl} 
          alt={symbol} 
          style={{ width: `${size}px`, height: `${size}px`, borderRadius: '50%', objectFit: 'contain' }}
          onError={(e) => {
            e.target.style.display = 'none';
            if (e.target.nextSibling) e.target.nextSibling.style.display = 'block';
          }}
        />
      ) : null}
      <span style={{ fontSize: `${Math.round(size * 0.75)}px`, display: logoUrl ? 'none' : 'block' }}>
        {fallbackIcon || '🪙'}
      </span>
    </div>
  );
}
